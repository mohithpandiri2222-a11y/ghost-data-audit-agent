"""
Tests for Rank 2: Case 03 Evidence-Backed Analytics Readback Verification.

Validates:
1. Case 03 produces the exact 3-step verification sequence matching sample_output.csv:
   - account_service account_7566 VERIFY_RECORD_ABSENT ABSENT evidence_94
   - security_service audit_record_2016 VERIFY_RECORD_PRESENT PRESENT evidence_94
   - analytics_platform analytics_9406 VERIFY_RECORD_ANONYMIZED ANONYMIZED evidence_94
2. Direct evidence grounding: evidence_94 confirms analytics_9406 has zero PII and account_7566 has http_status=404.
3. Negative test (unrelated users/cases): Unrelated users (e.g. user_44 in case_05) cannot inherit user_43's readbacks.
4. Negative test (temporal admissibility): Requests with audit_at prior to evidence_94 capture time reject the readback.
5. Negative test (wrong resource ID): Unverified / wrong resource IDs (e.g. analytics_4200) are never generated by planner.
6. Negative test (misleading log): A log with exposed PII or non-404 status is rejected by planner indexing.
"""

import tempfile
import unittest
from datetime import datetime, timezone
from pathlib import Path

from code.config import (
    SAMPLE_DELETION_REQUESTS_PATH,
    SAMPLE_OUTPUT_PATH,
    load_evidence_manifest,
    EvidenceFile,
)
from code.identity import SubjectIdentity
from code.planner import (
    AuditPlanner,
    DeletionRequest,
    STATUS_COMPLETE,
    load_deletion_requests,
)


class TestCase03Readback(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.manifest = load_evidence_manifest()
        cls.requests = {r.case_id: r for r in load_deletion_requests(SAMPLE_DELETION_REQUESTS_PATH)}
        cls.planner = AuditPlanner(manifest=cls.manifest)

    def test_case_03_exact_three_step_sequence(self):
        """Case 03 must match the exact 3 verification steps in sample_output.csv."""
        req = self.requests["case_03"]
        result = self.planner.audit_case(req)

        self.assertEqual(result.deletion_status, STATUS_COMPLETE)
        self.assertEqual(len(result.steps), 3)

        expected_steps = [
            ("account_service", "account_7566", "VERIFY_RECORD_ABSENT", "ABSENT", "evidence_94"),
            ("security_service", "audit_record_2016", "VERIFY_RECORD_PRESENT", "PRESENT", "evidence_94"),
            ("analytics_platform", "analytics_9406", "VERIFY_RECORD_ANONYMIZED", "ANONYMIZED", "evidence_94"),
        ]

        for idx, (sys_id, res_id, op, state, ev_id) in enumerate(expected_steps, start=1):
            step = result.steps[idx - 1]
            self.assertEqual(step.step_no, idx)
            self.assertEqual(step.phase, "VERIFICATION")
            self.assertEqual(step.system_id, sys_id)
            self.assertEqual(step.resource_id, res_id)
            self.assertEqual(step.operation, op)
            self.assertEqual(step.state, state)
            self.assertEqual(step.evidence_id, ev_id)

    def test_analytics_9406_evidence_grounding_zero_pii(self):
        """evidence_94 must directly confirm that analytics_9406 has zero direct PII."""
        ev_94 = self.manifest["evidence_94"]
        with open(ev_94.absolute_path, encoding="utf-8") as f:
            content = f.read()

        self.assertIn("resource_id=analytics_9406", content)
        self.assertIn("customer_reference=null", content)
        self.assertIn("email=null", content)
        self.assertIn("phone=null", content)
        self.assertIn("email_hash=null", content)
        self.assertIn("resource_id=account_7566", content)
        self.assertIn("http_status=404", content)

    def test_negative_unrelated_user_rejected(self):
        """Unrelated users/cases (e.g. user_44 in case_05) cannot inherit user_43's readback."""
        self.assertNotIn("user_44", self.planner.verified_readbacks_by_user)
        self.assertNotIn("user_99", self.planner.verified_readbacks_by_user)

        # Execute actual planner for case_05 (user_44)
        req_05 = self.requests["case_05"]
        res_05 = self.planner.audit_case(req_05)
        # Ensure analytics_9406 and account_7566 are never present in case_05 steps
        for step in res_05.steps:
            self.assertNotEqual(step.resource_id, "analytics_9406")
            self.assertNotEqual(step.resource_id, "account_7566")

    def test_negative_temporally_inadmissible_audit_at_rejected(self):
        """If audit_at is earlier than evidence_94 captured_at, readback step is excluded."""
        ev_94 = self.manifest["evidence_94"]
        pre_capture_audit_at = datetime(2026, 9, 20, 10, 0, tzinfo=timezone.utc)
        self.assertTrue(pre_capture_audit_at.isoformat() < ev_94.captured_at.isoformat())

        req = DeletionRequest(
            case_id="case_03_inadmissible_time",
            email="l.fontaine46@yahoo.com",
            requested_at=datetime(2026, 9, 13, 11, 0, tzinfo=timezone.utc),
            reported_status="COMPLETE",
            reported_at=datetime(2026, 9, 15, 11, 0, tzinfo=timezone.utc),
            audit_at=pre_capture_audit_at,
            request_text="Je demande la suppression définitive de mon compte.",
        )
        result = self.planner.audit_case(req)
        ev94_steps = [s for s in result.steps if s.evidence_id == "evidence_94"]
        self.assertEqual(len(ev94_steps), 0)

    def test_negative_wrong_resource_id_rejected(self):
        """Planner must not emit unverified or wrong resource IDs like analytics_4200."""
        req = self.requests["case_03"]
        result = self.planner.audit_case(req)
        step_resources = [s.resource_id for s in result.steps]
        self.assertNotIn("analytics_4200", step_resources)
        self.assertIn("analytics_9406", step_resources)

    def test_negative_misleading_log_rejected(self):
        """A misleading log containing exposed PII or non-404 status must be rejected during indexing."""
        with tempfile.NamedTemporaryFile("w+", suffix=".log", delete=False, encoding="utf-8") as tmp:
            # Misleading log: contains user_43 and analytics_9406 but exposes real PII
            tmp.write(
                "2026-09-26T08:57:37Z service=account_service resource_id=account_7566 http_status=200\n"
                "2026-09-26T09:54:09Z service=analytics_platform resource_id=analytics_9406 "
                "customer_reference=user_43 email=l.fontaine46@yahoo.com\n"
            )
            tmp_path = tmp.name

        try:
            fake_ev = EvidenceFile(
                file_id="evidence_94",
                file_path="evidence/logs/resource_lookup_trace_20260926_103856.log",
                origin="service_readback_logs",
                captured_at=datetime(2026, 9, 26, 10, 38, 56, tzinfo=timezone.utc),
                absolute_path=Path(tmp_path),
            )
            fake_manifest = dict(self.manifest)
            fake_manifest["evidence_94"] = fake_ev

            planner_with_misleading_log = AuditPlanner(manifest=fake_manifest)
            # The planner must reject this misleading log and NOT index user_43
            self.assertNotIn("user_43", planner_with_misleading_log.verified_readbacks_by_user)
        finally:
            Path(tmp_path).unlink(missing_ok=True)


if __name__ == "__main__":
    unittest.main()
